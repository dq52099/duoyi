#!/usr/bin/env python3
"""Generate Android rounded backgrounds from the actual Flutter widget palette.

Run from any directory: python3 scripts/generate_widget_surfaces.py
Then verify: flutter test test/services/home_widget_theme_resources_test.dart
"""

import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DRAWABLE = ROOT / 'android/app/src/main/res/drawable'
KOTLIN = ROOT / 'android/app/src/main/kotlin/com/duoyi/duoyi'


def blend(foreground, background, alpha):
    # Mirrors DuoyiWidgetTheme.blend: opaque RGB with integer channel truncation.
    front, back = int(foreground[1:], 16), int(background[1:], 16)
    channels = [int(((front >> shift) & 255) * alpha + ((back >> shift) & 255) * (1 - alpha)) for shift in (16, 8, 0)]
    return '#FF' + ''.join(f'{channel:02X}' for channel in channels)


def main():
    scratch = ROOT / '.dart_tool/widget-surface-generation'
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=scratch) as work:
        target = Path(work) / 'palettes.json'
        env = dict(os.environ, TMPDIR=str(scratch), DUOYI_EXPORT_WIDGET_PALETTES=str(target))
        subprocess.run([os.environ.get('FLUTTER_BIN', '/home/ubuntu/flutter/bin/flutter'), 'test', '--no-pub', 'test/services/home_widget_theme_resources_test.dart'], cwd=ROOT, env=env, check=True)
        palettes = json.loads(target.read_text())
    entries = []
    resources = {}
    mappings = []
    for palette in palettes:
        def value(key):
            return palette['widget_theme_' + key]
        key = f"{value('brand_id')}|{value('card_skin_id')}"
        surfaces = {}
        roles = {
            'root': (value('background'), value('border'), value('corner_radius_dp'), value('border_width_dp')),
            'nav': (value('nav_background'), blend(value('border'), value('nav_background'), .45), value('control_radius_dp'), int(value('border_width_dp') > 0)),
            'primary': (value('primary'), value('primary'), value('control_radius_dp'), 0),
            'secondary': (value('nav_background'), blend(value('border'), value('nav_background'), .35), value('control_radius_dp'), int(value('border_width_dp') > 0)),
            # A separate scalable layer stays visible above center-cropped images
            # and also works when the image decoder falls back to a solid surface.
            'imageBorder': ('#00000000', value('border'), value('corner_radius_dp'), value('border_width_dp')),
        }
        for role, (fill, stroke, radius, width) in roles.items():
            shape = dict(fill=fill, stroke=stroke if width else fill, radius=radius, strokeWidth=width)
            signature = json.dumps(shape, sort_keys=True)
            resource = 'widget_surface_' + hashlib.sha256(signature.encode()).hexdigest()[:16]
            resources[resource] = shape
            surfaces[role] = dict(shape, resource=resource)
        entries.append(dict(key=key, palette=palette, surfaces=surfaces))
        mappings.append(f'        "{key}" to Surfaces(' + ', '.join('R.drawable.' + surfaces[role]['resource'] for role in roles) + '),')
    for resource, shape in resources.items():
        stroke = f'    <stroke android:width="{shape["strokeWidth"]}dp" android:color="{shape["stroke"]}" />\n' if shape['strokeWidth'] else ''
        xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_widget_surfaces.py; do not hand edit. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <corners android:radius="{shape['radius']}dp" />
    <solid android:color="{shape['fill']}" />
{stroke}</shape>
'''
        (DRAWABLE / f'{resource}.xml').write_text(xml)
    output = '''package com.duoyi.duoyi

// Generated by scripts/generate_widget_surfaces.py from HomeWidgetThemePayload.
// R references keep the backgrounds reachable when resource shrinking is enabled.
internal object DuoyiWidgetSurfaceResources {
    data class Surfaces(val root: Int, val nav: Int, val primary: Int, val secondary: Int, val imageBorder: Int)

    private val palettes = mapOf(
''' + '\n'.join(mappings) + '''
    )

    fun forTheme(theme: DuoyiWidgetThemePalette): Surfaces? =
        palettes["${theme.brandId}|${theme.cardSkinId}"]
}
'''
    (KOTLIN / 'DuoyiWidgetSurfaceResources.kt').write_text(output)
    manifest = ROOT / 'android/app/src/main/res/raw/widget_surface_palettes.json'
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(json.dumps(entries, indent=2) + '\n')
    print(f'Generated {len(resources)} distinct rounded backgrounds for {len(entries)} palettes.')


if __name__ == '__main__':
    main()
